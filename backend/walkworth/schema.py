"""The one schema file.

SQLite tables (db.py) and the TypeScript types (web/src/types/schema.ts,
generated by scripts/gen_types.py) both follow these models. Edit here,
then run `npm run types`.

All timestamps are UTC. `Trek.tz` holds the zone used for display.
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class Model(BaseModel):
    # Fields with defaults are always present in API responses, so the
    # generated TypeScript marks them required.
    model_config = ConfigDict(json_schema_serialization_defaults_required=True)


class Landmark(Model):
    id: str
    name: str
    name_mr: str | None = None
    # Null until filled from OpenStreetMap. Never guessed.
    lat: float | None = None
    lon: float | None = None
    one_line: str = "TODO"
    osm_id: str | None = None


class FortPack(Model):
    id: str
    name: str
    name_mr: str | None = None
    landmarks: list[Landmark]
    glossary: list[str]


class Trek(Model):
    id: str
    title: str
    title_mr: str | None = None
    fort_pack_id: str | None = None
    started_at: datetime
    ended_at: datetime | None = None
    tz: str = "Asia/Kolkata"
    screen_seconds: int | None = None
    model_versions: dict[str, str] = Field(default_factory=dict)
    # True while any part of the trek comes from fixtures/. Drives the
    # "Sample data" ribbon.
    is_sample: bool = False
    # Added to every photo and voice-note time before aligning to the GPX,
    # to correct phone/GPS clock drift. Set on the Import screen.
    time_offset_s: int = 0


class TrackPoint(Model):
    trek_id: str
    t: datetime
    lat: float
    lon: float
    ele_m: float | None = None


LocationSource = Literal["fix", "track", "none"]


class Word(Model):
    w: str
    start: float
    end: float
    # Scribe's word probability, 0..1 (from its log-probability). Below 0.6 is
    # underlined in Review. None when the service didn't report one.
    p: float | None = None


class VoiceNote(Model):
    id: str
    trek_id: str
    t: datetime
    # Null when the GPS fix timed out; aligned later by timestamp.
    lat: float | None = None
    lon: float | None = None
    location_source: LocationSource = "fix"
    ele_m: float | None = None
    landmark_id: str | None = None
    audio_path: str | None = None
    duration_s: float
    transcript: str | None = None
    words: list[Word] = Field(default_factory=list)
    lang: str | None = None
    translation: str | None = None
    confidence: float | None = None
    # Why the note has no transcript, e.g. "no speech" from the VAD.
    skipped: str | None = None
    # From the Extract step.
    mood: str | None = None
    quote: str | None = None
    user_edited: bool = False


class Photo(Model):
    id: str
    trek_id: str
    t: datetime
    lat: float | None = None
    lon: float | None = None
    path: str
    sha256: str
    location_source: LocationSource = "fix"
    ele_m: float | None = None
    landmark_id: str | None = None
    caption: str | None = None
    caption_source_ids: list[str] = Field(default_factory=list)
    # Set only for photos that aren't the user's (the sample's Commons
    # photos). Rendered under the print.
    credit: str | None = None
    # Set in Review when the user drags a photo to a different note.
    pinned_note_id: str | None = None
    # True once the user edits the caption; regeneration then leaves it alone.
    user_edited: bool = False


ObservationKind = Literal["wildlife", "plant", "structure", "view", "weather", "people", "feeling"]


class Observation(Model):
    id: str
    note_id: str
    kind: ObservationKind
    text: str
    landmark_id: str | None = None


class Entry(Model):
    id: str
    trek_id: str
    chapter: str
    t: datetime
    ele_m: float | None = None
    note_id: str | None = None
    photo_ids: list[str] = Field(default_factory=list)
    landmark_id: str | None = None
    quote: str | None = None


GeneratedLineRole = Literal["opener", "chapter_title", "chapter_line"]


class GeneratedLine(Model):
    id: str
    trek_id: str
    role: GeneratedLineRole
    # Chapter key for chapter_title and chapter_line; null for the opener.
    chapter: str | None = None
    text: str
    # A line with no sources is dropped before render. See the grounding rule.
    # "user" means the user wrote or rewrote it in Review.
    source_ids: list[str] = Field(default_factory=list)
    user_edited: bool = False


# ---- API views -------------------------------------------------------------


class TrekStats(Model):
    distance_m: float
    gain_m: float
    high_point_m: float | None = None
    total_s: int
    moving_s: int


class RoutePoint(Model):
    lat: float
    lon: float
    ele_m: float | None = None


class TrekSummary(Model):
    trek: Trek
    stats: TrekStats | None = None
    note_count: int
    photo_count: int
    # Downsampled for thumbnails and contour backgrounds.
    route: list[RoutePoint]
    # True once the pipeline has composed the journal.
    processed: bool = False
    # True when this browser may change the trek (see access.py). The sample
    # is read-only for everyone.
    can_edit: bool = False


ImportKind = Literal["gpx", "photo", "audio", "unknown"]


class ImportResult(Model):
    name: str
    kind: ImportKind
    # added: stored; duplicate: already had it; skipped: not usable
    status: Literal["added", "duplicate", "skipped"]
    detail: str | None = None


StepStatus = Literal["waiting", "running", "done", "failed"]


class PipelineStep(Model):
    key: str
    label: str
    status: StepStatus = "waiting"
    done: int = 0
    total: int = 0
    model: str | None = None
    detail: str | None = None


class ProcessStatus(Model):
    workflow_id: str | None = None
    state: Literal["not_started", "running", "completed", "failed"]
    steps: list[PipelineStep] = Field(default_factory=list)
    error: str | None = None


