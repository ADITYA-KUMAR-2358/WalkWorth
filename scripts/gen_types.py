"""Generates web/src/types/schema.ts from backend/walkworth/schema.py.

    npm run types
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from pydantic.json_schema import models_json_schema  # noqa: E402

from walkworth.schema import EXPORTED  # noqa: E402

OUT = ROOT / "web" / "src" / "types" / "schema.ts"


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in s:
        return " | ".join(ts_type(x) for x in s["anyOf"])
    if "enum" in s:
        return " | ".join(f'"{v}"' for v in s["enum"])
    if "const" in s:
        return f'"{s["const"]}"'
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        extra = s.get("additionalProperties")
        return f"Record<string, {ts_type(extra)}>" if isinstance(extra, dict) else "Record<string, unknown>"
    return "unknown"


def main() -> None:
    _, top = models_json_schema([(m, "serialization") for m in EXPORTED], ref_template="#/$defs/{model}")
    defs = top["$defs"]
    lines = [
        "// Generated by scripts/gen_types.py from backend/walkworth/schema.py.",
        "// Do not edit by hand. Run `npm run types`.",
        "",
    ]
    for model in EXPORTED:
        schema = defs[model.__name__]
        required = set(schema.get("required", []))
        lines.append(f"export interface {model.__name__} {{")
        for name, prop in schema["properties"].items():
            opt = "" if name in required else "?"
            lines.append(f"  {name}{opt}: {ts_type(prop)};")
        lines += ["}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
